"""Summarise raw/<config>/*.json into results-data.md (numbers + side-by-side picks). results.md is written by hand on top of this."""
import json
import os
import statistics as st

HERE = os.path.dirname(os.path.abspath(__file__))
RAW = os.path.join(HERE, "raw")


def load():
    cfgs = {}
    for cfg in sorted(os.listdir(RAW)):
        d = os.path.join(RAW, cfg)
        if not os.path.isfile(os.path.join(d, "summary.json")):
            continue
        summ = json.load(open(os.path.join(d, "summary.json"), encoding="utf-8"))
        recs = [json.load(open(os.path.join(d, f"{p}.json"), encoding="utf-8")) for p in summ["photos"]]
        cfgs[cfg] = (summ, recs)
    return cfgs


def mean(xs):
    xs = [x for x in xs if x is not None]
    return round(st.mean(xs), 1) if xs else None


def pct(xs):
    return f"{sum(xs)}/{len(xs)} ({100 * sum(xs) / len(xs):.0f}%)" if xs else "-"


def main():
    cfgs = load()
    L = ["# Raw numbers (generated by analyze.py)", ""]
    L += ["| config | load s | describe s | pick s | gen tok/s | describe gen tokens | pick gen tokens | pick prompt tok/s | JSON strict | JSON lenient | schema OK | top-3 overlap (mean /3) | top-1 same | on-topic share of picks | strengths seen |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for cfg, (s, recs) in cfgs.items():
        calls = [r[k] for r in recs for k in ("describe", "pick1", "pick2")]
        picks = [p for r in recs for k in ("pick1", "pick2") for p in r[k]["picks"]]
        strengths = sorted({p["strength"] for p in picks if isinstance(p["strength"], (int, float))})
        L.append("| {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} |".format(
            cfg, s["load_s"], mean([r["describe"]["wall_s"] for r in recs]),
            mean([r[k]["wall_s"] for r in recs for k in ("pick1", "pick2")]),
            mean([c["gen_tps"] for c in calls]),
            mean([r["describe"]["gen_n"] for r in recs]), mean([r[k]["gen_n"] for r in recs for k in ("pick1", "pick2")]),
            mean([r[k]["prompt_tps"] for r in recs for k in ("pick1", "pick2")]),
            pct([c["strict_ok"] for c in calls]), pct([c["lenient_ok"] for c in calls]), pct([c["schema_ok"] for c in calls]),
            mean([r["overlap"] for r in recs]), pct([r["top1_same"] for r in recs]),
            pct([p["on_topic"] for p in picks]), ", ".join(str(x) for x in strengths)))
    L.append("")
    L.append("Reasoning tokens are included in gen tokens (llama-server counts them in predicted_n).")
    L.append("")
    # finish reasons / failures
    for cfg, (s, recs) in cfgs.items():
        bad = [(r["photo"], k, r[k]["finish"], r[k]["content"][:160].replace("\n", " "))
               for r in recs for k in ("describe", "pick1", "pick2") if not r[k]["schema_ok"]]
        if bad:
            L.append(f"**{cfg} schema failures:**")
            for b in bad:
                L.append(f"- {b[0]} {b[1]} (finish={b[2]}): `{b[3]}`")
            L.append("")
    # cross-model agreement on pick1
    names = list(cfgs)
    if len(names) > 1:
        L.append("## Cross-config agreement (pick1 top-3 overlap, mean /3)")
        L.append("")
        for i, a in enumerate(names):
            for b in names[i + 1:]:
                ra = {r["photo"]: r for r in cfgs[a][1]}
                rb = {r["photo"]: r for r in cfgs[b][1]}
                ov = [len({p["key"] for p in ra[p_]["pick1"]["picks"]} & {p["key"] for p in rb[p_]["pick1"]["picks"]}) for p_ in ra if p_ in rb]
                L.append(f"- {a} vs {b}: {mean(ov)}")
        L.append("")
    # per photo side by side
    photos = cfgs[names[0]][1]
    for r0 in photos:
        pid = r0["photo"]
        L.append(f"## {pid}")
        L.append("")
        for cfg in names:
            rec = next((r for r in cfgs[cfg][1] if r["photo"] == pid), None)
            if rec is None:
                continue
            d = rec["describe"]["parsed"] or {}
            L.append(f"**{cfg}** — describe: contrast={d.get('contrast')}; issues={d.get('issues')}; style={d.get('style_directions')}")
            L.append(f"  - color_tone: {d.get('color_tone')}")
            for k in ("pick1", "pick2"):
                L.append(f"  - {k}: " + " / ".join(f"{p['key']} {p['label']}{' *' if p['on_topic'] else ''} @{p['strength']}" for p in rec[k]["picks"]))
            for p in rec["pick1"]["picks"]:
                L.append(f"    - {p['key']}: {p['reason']}")
            L.append(f"  - overlap {rec['overlap']}/3, top-1 same: {rec['top1_same']}")
        L.append("")
    with open(os.path.join(HERE, "results-data.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    print("\n".join(L[:12]))


if __name__ == "__main__":
    main()
